//! Trusted observer adapter boundary and conservative geodesic transformation.
//! An adapter must authenticate the evidence; browser GPS/BLE alone is not trusted.
use crate::{Blinding, Context, Disclosure, DispatchState, Error, Guarantee, Proof, State};
use cfbk::cost::{DispatchPermit, Mode, Price, Quote};
use geographiclib_rs::{Geodesic, InverseGeodesic};
use sha2::{Digest, Sha256};

/// Latitude/longitude and an explicit hard accuracy bound, in meters.
/// Probabilistic GPS confidence is not a hard bound unless the caller accepts it.
pub struct Position {
    /// Degrees north, within [-90, 90].
    pub latitude: f64,
    /// Degrees east, within [-180, 180].
    pub longitude: f64,
    /// Nonnegative finite uncertainty radius.
    pub accuracy_m: f64,
}
impl Position {
    fn validate(&self) -> bool {
        (-90.0..=90.0).contains(&self.latitude)
            && (-180.0..=180.0).contains(&self.longitude)
            && self.accuracy_m.is_finite()
            && self.accuracy_m >= 0.0
    }
}

/// Requirement chosen by the caller before selecting adapters.
pub enum Requirement<'a> {
    /// Observer must attest this other party; self-encounters are rejected.
    Encounter {
        /// Expected authenticated counterpart, within the configured observer's identity domain.
        peer: &'a str,
    },
    /// The full uncertainty region must fall within the allowed radius.
    Distance {
        /// Trusted target coordinates and target uncertainty.
        target: Position,
        /// Nonnegative finite allowed radius in meters.
        radius_m: f64,
    },
}

/// Authenticated observation returned ONLY by the trusted adapter, never member JSON.
pub struct Observation {
    /// Stable verified subject in the adapter's identity domain.
    pub subject: String,
    /// Authenticated opaque request context supplied to the adapter.
    pub context: String,
    /// Globally unique authenticated observation ID for replay prevention.
    pub id: String,
    /// Authenticated observation timestamp, Unix seconds.
    pub observed_at: u64,
    /// Observed counterpart, when the mechanism establishes an encounter.
    pub peer: Option<String>,
    /// Observed position, when the mechanism establishes location.
    pub position: Option<Position>,
    /// All upstream data; not additional authenticated claims by implication.
    pub upstream: serde_json::Value,
}

/// Trusted mechanism adapter. This port supports readers, location attesters and
/// authenticated member encounters without inventing a universal proximity protocol.
pub trait Adapter {
    /// Stable adapter/account identity; no credential discovery.
    fn id(&self) -> &str;
    /// Production or provider sandbox; never local simulation.
    fn mode(&self) -> Mode;
    /// Authenticate the observation and bind it to `context`. Before this provider
    /// call the library has required atomic host dispatch/budget reservation.
    /// No implicit retries, unpriced I/O or logging of private evidence.
    fn verify(
        &self,
        evidence: &[u8],
        context: &str,
        quote: &Quote,
    ) -> impl std::future::Future<Output = Result<Observation, Error>>;
}

/// Requirements bound into one dispatch preview.
pub struct Request<'a> {
    /// Caller scope and registration quota.
    pub context: Context<'a>,
    /// Expected authenticated subject, supplied by the application.
    pub subject: &'a str,
    /// Fresh opaque context generated by the host and authenticated by the adapter.
    pub nonce: &'a str,
    /// Maximum accepted age of the authenticated observation, seconds.
    pub max_age: u64,
    /// Required mechanism-specific predicate.
    pub requirement: Requirement<'a>,
}

impl Request<'_> {
    pub(crate) fn validate(&self, now: u64) -> Result<(), Error> {
        self.context.validate(now)?;
        if self.subject.is_empty() || self.nonce.is_empty() || self.max_age == 0 {
            return Err(Error::Configuration);
        }
        let valid = match &self.requirement {
            Requirement::Encounter { peer } => !peer.is_empty() && *peer != self.subject,
            Requirement::Distance { target, radius_m } => {
                target.validate() && radius_m.is_finite() && *radius_m >= 0.0
            }
        };
        if !valid {
            return Err(Error::Configuration);
        }
        Ok(())
    }
    /// Opaque context adapters must authenticate, covering all trusted requirements.
    pub fn binding(&self) -> String {
        let terms = match &self.requirement {
            Requirement::Encounter { peer } => serde_json::json!(["encounter", peer]),
            Requirement::Distance { target, radius_m } => serde_json::json!([
                "distance",
                target.latitude.to_bits(),
                target.longitude.to_bits(),
                target.accuracy_m.to_bits(),
                radius_m.to_bits()
            ]),
        };
        hex::encode(Sha256::digest(
            serde_json::to_vec(&serde_json::json!([
                "cpxm.observation.v1",
                self.context.scope,
                self.context.registration,
                self.context.maximum,
                self.context.expires,
                self.subject,
                self.nonce,
                self.max_age,
                terms
            ]))
            .expect("JSON values serialize"),
        ))
    }
}

fn binding(adapter: &impl Adapter, request: &Request<'_>, evidence: &[u8]) -> String {
    hex::encode(Sha256::digest(
        serde_json::to_vec(&serde_json::json!([
            "cpxm.dispatch.v1",
            adapter.id(),
            format!("{:?}", adapter.mode()),
            request.binding(),
            hex::encode(Sha256::digest(evidence))
        ]))
        .expect("JSON values serialize"),
    ))
}

pub(crate) fn evaluate(
    request: &Request<'_>,
    result: &Observation,
    now: u64,
) -> Result<Guarantee, Error> {
    if result.subject != request.subject
        || result.context != request.binding()
        || result.id.is_empty()
        || result.observed_at > now
        || now - result.observed_at > request.max_age
    {
        return Err(Error::Rejected);
    }
    let guarantee = match &request.requirement {
        Requirement::Encounter { peer } => {
            if result.peer.as_deref() != Some(*peer) {
                return Err(Error::Rejected);
            }
            Guarantee::ObserverEncounter
        }
        Requirement::Distance { target, radius_m } => {
            let position = result.position.as_ref().ok_or(Error::Rejected)?;
            if !position.validate() {
                return Err(Error::Rejected);
            }
            let distance: f64 = Geodesic::wgs84().inverse(
                target.latitude,
                target.longitude,
                position.latitude,
                position.longitude,
            );
            // Positive inclusion also rejects NaN from any unexpected upstream failure.
            let within = distance + target.accuracy_m + position.accuracy_m <= *radius_m;
            if !within {
                return Err(Error::Rejected);
            }
            Guarantee::ObserverDistance
        }
    };
    Ok(guarantee)
}

/// Pure sourced cost preview. Unknown cost cannot authorize a cfbk dispatch permit.
pub fn preview(
    adapter: &impl Adapter,
    request: &Request<'_>,
    evidence: &[u8],
    price: Price,
    source: String,
    valid_until: u64,
    now: u64,
) -> Result<Quote, Error> {
    request.validate(now)?;
    Ok(Quote {
        price,
        source,
        valid_until: valid_until.min(request.context.expires),
        binding: binding(adapter, request, evidence),
    })
}

/// Domain service holds only the adapter and a RAM blinding key.
pub struct Service<A> {
    /// Trusted authenticated-observation adapter.
    pub adapter: A,
    /// Identity domain must correspond to the adapter's actual subject namespace.
    pub blinding: Blinding,
}

/// Provider sandbox outputs cannot mint production proofs.
pub enum Verified {
    /// Production verification succeeded and host state reserved the registration.
    Production {
        /// Minimal domain result.
        proof: Proof,
        /// Complete provider information when requested.
        upstream: Option<serde_json::Value>,
    },
    /// Explicit provider sandbox response, never production evidence.
    Sandbox {
        /// Complete provider information when requested.
        upstream: Option<serde_json::Value>,
    },
}
impl<A: Adapter> Service<A> {
    /// Verify under a bound permit, transform, then atomically reserve opaque state.
    pub async fn verify(
        &self,
        request: &Request<'_>,
        evidence: &[u8],
        permit: DispatchPermit<String>,
        state: &mut (impl State + DispatchState),
        disclosure: Disclosure,
        now: u64,
    ) -> Result<Verified, Error> {
        request.validate(now)?;
        if evidence.len() > 65536 || self.adapter.mode() == Mode::Simulation {
            return Err(Error::Rejected);
        }
        permit
            .validate(
                &binding(&self.adapter, request, evidence),
                self.adapter.mode(),
                now,
            )
            .map_err(|_| Error::Cost)?;
        if permit.candidate() != self.adapter.id() {
            return Err(Error::Cost);
        }
        if !state.reserve_dispatch(permit.quote()) {
            return Err(Error::Cost);
        }
        let result = self
            .adapter
            .verify(evidence, &request.binding(), permit.quote())
            .await?;
        let guarantee = evaluate(request, &result, now)
            .map_err(|error| error.with_report(disclosure, result.upstream.clone()))?;
        if self.adapter.mode() == Mode::Sandbox {
            return Ok(Verified::Sandbox {
                upstream: (disclosure == Disclosure::Complete).then_some(result.upstream),
            });
        }
        let identity = self.blinding.key(
            "observer-subject",
            request.context.scope,
            result.subject.as_bytes(),
        );
        let evidence = self
            .blinding
            .key("observer-replay", "", result.id.as_bytes());
        if !state.reserve(&identity, &evidence, None, &request.context) {
            return Err(Error::State.with_report(disclosure, result.upstream));
        }
        Ok(Verified::Production {
            proof: Proof {
                guarantee,
                expires: request.context.expires,
            },
            upstream: (disclosure == Disclosure::Complete).then_some(result.upstream),
        })
    }
}
